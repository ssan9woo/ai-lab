import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'package:flutter_nl_verify/verify/nl_parser.dart';

const _resultStartMarker = '===NL_VERIFY_RESULT_START===';
const _resultEndMarker = '===NL_VERIFY_RESULT_END===';
const _generatedTestPath = 'integration_test/generated_run.dart';

Future<void> main(List<String> arguments) async {
  if (arguments.length != 1 || arguments.single.trim().isEmpty) {
    stderr.writeln('Usage: ./verify "<natural language instruction>"');
    exitCode = 64;
    return;
  }

  final instruction = arguments.single;
  try {
    stdout.writeln('Parsing natural-language instruction...');
    final plan = await parseNaturalLanguage(instruction);
    final planJson = jsonEncode([for (final action in plan) action.toJson()]);
    await File(_generatedTestPath).writeAsString(_testSource(planJson));

    final device = await _findOrBootSimulator();
    stdout.writeln('Running ${plan.length} action(s) on ${device.name}...');
    final execution = await _runFlutterTest(device.udid);
    final result = _extractResult(execution.stdoutText);
    final evidenceDirectory = await _writeEvidence(
      instruction: instruction,
      planJson: planJson,
      result: result,
    );

    _printSummary(result);
    stdout.writeln('Evidence: ${evidenceDirectory.path}');
    if (execution.exitCode != 0 && result['passed'] == true) {
      stderr.writeln('flutter test exited with code ${execution.exitCode}.');
      exitCode = 1;
    } else {
      exitCode = result['passed'] == true ? 0 : 1;
    }
  } catch (error) {
    stderr.writeln('NL verify failed: $error');
    exitCode = 1;
  }
}

String _testSource(String planJson) {
  final literal = jsonEncode(planJson).replaceAll(r'$', r'\$');
  return '''// Generated by bin/verify.dart. Do not edit or commit.
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:flutter_nl_verify/main.dart' as app;
import 'package:flutter_nl_verify/verify/action.dart';
import 'support/runner.dart';

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('nl verify run', (tester) async {
    app.main();
    await tester.pumpAndSettle();
    final plan = parseActionPlan($literal);
    final result = await runActionPlan(tester, plan);
    printNlVerifyResult(result);
  });
}
''';
}

Future<_Simulator> _findOrBootSimulator() async {
  final listing = await Process.run('xcrun', const [
    'simctl',
    'list',
    'devices',
    'available',
    '--json',
  ]);
  if (listing.exitCode != 0) {
    throw StateError('Could not list iOS simulators: ${listing.stderr}');
  }

  final decoded = jsonDecode(listing.stdout as String) as Map<String, dynamic>;
  final runtimes = decoded['devices'] as Map<String, dynamic>;
  final simulators = <_Simulator>[];
  for (final entry in runtimes.entries) {
    if (!entry.key.contains('iOS')) continue;
    for (final raw in entry.value as List<dynamic>) {
      final device = raw as Map<String, dynamic>;
      final name = device['name'] as String;
      if (name.contains('iPhone')) {
        simulators.add(
          _Simulator(
            name: name,
            udid: device['udid'] as String,
            isBooted: device['state'] == 'Booted',
          ),
        );
      }
    }
  }
  if (simulators.isEmpty) {
    throw StateError('No available iOS iPhone simulator was found.');
  }

  final booted = simulators.where((device) => device.isBooted);
  if (booted.isNotEmpty) return booted.first;

  final selected = simulators.first;
  stdout.writeln('Booting ${selected.name}...');
  final boot = await Process.run('xcrun', ['simctl', 'boot', selected.udid]);
  if (boot.exitCode != 0) {
    throw StateError('Could not boot ${selected.name}: ${boot.stderr}');
  }
  final ready = await Process.run('xcrun', [
    'simctl',
    'bootstatus',
    selected.udid,
    '-b',
  ]);
  if (ready.exitCode != 0) {
    throw StateError('Simulator did not finish booting: ${ready.stderr}');
  }
  return selected;
}

Future<_Execution> _runFlutterTest(String udid) async {
  final process = await Process.start('flutter', [
    'test',
    _generatedTestPath,
    '-d',
    udid,
  ]);
  final stdoutFuture = process.stdout.transform(utf8.decoder).join();
  final stderrFuture = process.stderr.transform(utf8.decoder).join();
  final code = await process.exitCode;
  final stdoutText = await stdoutFuture;
  final stderrText = await stderrFuture;
  if (stderrText.trim().isNotEmpty) stderr.write(stderrText);
  return _Execution(
    exitCode: code,
    stdoutText: stdoutText,
    stderrText: stderrText,
  );
}

Map<String, dynamic> _extractResult(String output) {
  final start = output.indexOf(_resultStartMarker);
  if (start < 0) {
    throw StateError(
      'flutter test output did not contain the result start marker.',
    );
  }
  final jsonStart = start + _resultStartMarker.length;
  final end = output.indexOf(_resultEndMarker, jsonStart);
  if (end < 0) {
    throw StateError(
      'flutter test output did not contain the result end marker.',
    );
  }
  final decoded = jsonDecode(output.substring(jsonStart, end));
  if (decoded is! Map<String, dynamic> || decoded['steps'] is! List<dynamic>) {
    throw const FormatException('Runner result has an invalid shape.');
  }
  final steps = decoded['steps'] as List<dynamic>;
  return {
    ...decoded,
    'passed': steps.every((raw) => (raw as Map)['passed'] == true),
  };
}

Future<Directory> _writeEvidence({
  required String instruction,
  required String planJson,
  required Map<String, dynamic> result,
}) async {
  final now = DateTime.now();
  String two(int value) => value.toString().padLeft(2, '0');
  final stamp =
      '${now.year}${two(now.month)}${two(now.day)}_'
      '${two(now.hour)}${two(now.minute)}${two(now.second)}';
  var directory = Directory('evidence/$stamp');
  var suffix = 1;
  while (await directory.exists()) {
    directory = Directory('evidence/${stamp}_$suffix');
    suffix++;
  }
  await directory.create(recursive: true);
  const encoder = JsonEncoder.withIndent('  ');
  await File(
    '${directory.path}/instruction.txt',
  ).writeAsString('$instruction\n');
  await File(
    '${directory.path}/plan.json',
  ).writeAsString('${encoder.convert(jsonDecode(planJson))}\n');
  await File(
    '${directory.path}/result.json',
  ).writeAsString('${encoder.convert(result)}\n');
  return directory;
}

void _printSummary(Map<String, dynamic> result) {
  final steps = result['steps'] as List<dynamic>;
  final passed = steps.where((raw) => (raw as Map)['passed'] == true).length;
  final totalMs = steps.fold<int>(
    0,
    (sum, raw) => sum + ((raw as Map)['durationMs'] as int),
  );
  stdout.writeln('\nNL Verify Summary');
  stdout.writeln(
    'Steps: ${steps.length} | Passed: $passed | Failed: ${steps.length - passed}',
  );
  stdout.writeln('Total duration: ${totalMs}ms');
  for (final raw in steps) {
    final step = raw as Map<String, dynamic>;
    final action = step['action'] as Map<String, dynamic>;
    final target = action['target'] as Map<String, dynamic>;
    final mark = step['passed'] == true ? '✓' : '✗';
    stdout.writeln(
      '$mark ${action['action']}(${target['value']}) ${step['durationMs']}ms',
    );
    if (step['error'] != null) stdout.writeln('  ${step['error']}');
  }
}

final class _Simulator {
  const _Simulator({
    required this.name,
    required this.udid,
    required this.isBooted,
  });
  final String name;
  final String udid;
  final bool isBooted;
}

final class _Execution {
  const _Execution({
    required this.exitCode,
    required this.stdoutText,
    required this.stderrText,
  });
  final int exitCode;
  final String stdoutText;
  final String stderrText;
}
